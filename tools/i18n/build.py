#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Builds the Java .properties bundles from the python sources and checks key parity.

Usage:  python3 tools/i18n/build.py
The French bundle is the reference: every other language must contain the same keys.
"""
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TARGET = os.path.join(HERE, "..", "..", "src", "main", "resources", "i18n")
sys.path.insert(0, HERE)

import ar  # noqa: E402
import en  # noqa: E402
import fr  # noqa: E402

BUNDLES = {"fr": fr.MESSAGES, "ar": ar.MESSAGES, "en": en.MESSAGES}
REFERENCE = fr.MESSAGES


def write_bundle(language, messages):
    path = os.path.join(TARGET, "messages_%s.properties" % language)
    with io.open(path, "w", encoding="utf-8") as handle:
        handle.write("# ChemManager ERP - %s messages\n" % language)
        handle.write("# generated by tools/i18n/build.py - do not edit directly\n")
        for key in sorted(messages):
            value = messages[key].replace("\n", "\\n")
            handle.write("%s=%s\n" % (key, value))
    return path


def main():
    problems = []
    for language, messages in BUNDLES.items():
        for key in REFERENCE:
            if key not in messages:
                problems.append("%s: missing key %s" % (language, key))
        for key, value in messages.items():
            if key not in REFERENCE:
                problems.append("%s: unexpected key %s" % (language, key))
            if value.count("{") != value.count("}"):
                problems.append("%s: unbalanced placeholders in %s" % (language, key))
    if problems:
        print("\n".join(problems))
        return 1
    for language, messages in BUNDLES.items():
        path = write_bundle(language, messages)
        print("wrote %s (%d keys)" % (os.path.basename(path), len(messages)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
