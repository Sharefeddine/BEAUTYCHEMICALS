    /**
     * @param array<string,mixed> $document payload built by the sales repository
     * @param array<string,mixed>|null $company the company identity printed in the header
     */
    public function render(array $document, ?array $company): string
    {
        $lang = in_array($document['lang'] ?? 'fr', ['fr', 'en', 'ar'], true) ? (string) $document['lang'] : 'fr';
        $labels = self::LABELS[$lang];
        $rtl = $lang === 'ar';
        $title = $labels[strtolower((string) $document['type'])];
        $currency = (string) ($company['currency'] ?? 'DZD');

        $html = [];
        $html[] = '<!DOCTYPE html>';
        $html[] = '<html lang="' . $lang . '" dir="' . ($rtl ? 'rtl' : 'ltr') . '">';
        $html[] = '<head><meta charset="utf-8"><title>' . $this->escape($title . ' ' . $document['number'])
            . '</title><style>' . $this->style($document['type']) . '</style></head>';
        $html[] = '<body>';
        $html[] = '<div class="sheet">';

        // Letterhead
        $html[] = '<header class="head">';
        $html[] = '<div class="company">';
        $html[] = '<div class="company-name">' . $this->escape((string) ($company['name'] ?? 'ChemManager')) . '</div>';
        if (!empty($company['legalName'])) {
            $html[] = '<div class="company-legal">' . $this->escape((string) $company['legalName']) . '</div>';
        }
        $address = trim(implode(' ', array_filter([
            (string) ($company['address'] ?? ''),
            (string) ($company['postalCode'] ?? ''),
            (string) ($company['city'] ?? ''),
            (string) ($company['wilaya'] ?? ''),
        ])));
        if ($address !== '') {
            $html[] = '<div>' . $this->escape($address) . '</div>';
        }
        $contacts = array_filter([
            (string) ($company['phone'] ?? ''),
            (string) ($company['email'] ?? ''),
            (string) ($company['website'] ?? ''),
        ]);
        if ($contacts !== []) {
            $html[] = '<div>' . $this->escape(implode(' · ', $contacts)) . '</div>';
        }
        $legal = [];
        foreach (['rc' => 'tradeRegister', 'nif' => 'nif', 'ai' => 'taxArticle'] as $label => $field) {
            if (!empty($company[$field])) {
                $legal[] = $labels[$label] . ' ' . (string) $company[$field];
            }
        }
        if ($legal !== []) {
            $html[] = '<div class="company-legal">' . $this->escape(implode(' · ', $legal)) . '</div>';
        }
        $html[] = '</div>';

        $html[] = '<div class="doc-title">';
        $html[] = '<div class="doc-type">' . $this->escape($title) . '</div>';
        $html[] = '<div class="doc-number">' . $this->escape((string) $document['number']) . '</div>';
        $html[] = '<table class="doc-meta">';
        $html[] = '<tr><th>' . $labels['date'] . '</th><td>' . $this->escape($this->date($document['date']))
            . '</td></tr>';
        if (!empty($document['secondaryDate'])) {
            $key = (string) ($document['secondaryDateLabel'] ?? 'date');
            $html[] = '<tr><th>' . $this->escape($labels[$key] ?? $key) . '</th><td>'
                . $this->escape($this->date($document['secondaryDate'])) . '</td></tr>';
        }
        if ($document['type'] !== 'STATEMENT') {
            $html[] = '<tr><th>' . $labels['status'] . '</th><td>' . $this->escape((string) $document['status'])
                . '</td></tr>';
        }
        $html[] = '</table></div>';
        $html[] = '</header>';

        // Customer block
        $customer = $document['customer'];
        $html[] = '<section class="party">';
        $html[] = '<div class="party-label">' . $labels['customer'] . '</div>';
        $html[] = '<div class="party-name">' . $this->escape((string) $customer['name']) . '</div>';
        $details = [];
        if (($customer['code'] ?? '') !== '') {
            $details[] = $labels['code'] . ' ' . (string) $customer['code'];
        }
        if (($customer['address'] ?? '') !== '') {
            $details[] = (string) $customer['address'];
        }
        if (($customer['wilaya'] ?? '') !== '') {
            $details[] = (string) $customer['wilaya'];
        }
        if (($customer['phone'] ?? '') !== '') {
            $details[] = $labels['phone'] . ' ' . (string) $customer['phone'];
        }
        if ($details !== []) {
            $html[] = '<div class="party-details">' . $this->escape(implode(' · ', $details)) . '</div>';
        }
        if (!empty($document['reference'])) {
            $html[] = '<div class="party-details">' . $labels['reference'] . ' : '
                . $this->escape((string) $document['reference']) . '</div>';
        }
        $html[] = '</section>';

        $html[] = match ($document['type']) {
            'STATEMENT' => $this->statementTable($document, $labels, $currency),
            default => $this->itemsTable($document, $labels, $currency),
        };

        if (($document['notes'] ?? '') !== '') {
            $html[] = '<section class="notes"><span class="notes-label">' . $labels['notes'] . '</span> '
                . $this->escape((string) $document['notes']) . '</section>';
        }

        if ($document['type'] === 'DELIVERY') {
            $html[] = '<section class="signature">';
            $html[] = '<div><span class="notes-label">' . $labels['signedBy'] . '</span> '
                . $this->escape((string) ($document['extra']['signedBy'] ?? '')) . '</div>';
            $html[] = '<div class="signature-box">' . $labels['signature'] . '</div>';
            $html[] = '</section>';
        }

        $html[] = '<footer class="foot">' . $this->escape($labels['printedBy']) . ' · '
            . $this->escape(date('d/m/Y H:i')) . '</footer>';
        $html[] = '</div></body></html>';

        return implode("\n", $html);
    }

    /**
     * @param array<string,mixed> $document
     * @param array<string,string> $labels
     */
    private function itemsTable(array $document, array $labels, string $currency): string
    {
        $showPrices = $document['type'] !== 'DELIVERY';
        $html = [];
        $html[] = '<table class="lines"><thead><tr>';
        $html[] = '<th class="num">#</th>';
        $html[] = '<th>' . $labels['designation'] . '</th>';
        $html[] = '<th>' . $labels['batch'] . '</th>';
        $html[] = '<th class="right">' . $labels['quantity'] . '</th>';
        $html[] = '<th>' . $labels['unit'] . '</th>';
        if ($showPrices) {
            $html[] = '<th class="right">' . $labels['unitPrice'] . '</th>';
            $html[] = '<th class="right">' . $labels['discount'] . '</th>';
            $html[] = '<th class="right">' . $labels['vat'] . '</th>';
            $html[] = '<th class="right">' . $labels['lineTotal'] . '</th>';
        }
        $html[] = '</tr></thead><tbody>';

        $index = 0;
        foreach ($document['items'] as $item) {
            $index++;
            $html[] = '<tr>';
            $html[] = '<td class="num">' . $index . '</td>';
            $html[] = '<td><strong>' . $this->escape((string) $item['productCode']) . '</strong> — '
                . $this->escape((string) $item['productName']) . '</td>';
            $html[] = '<td>' . $this->escape((string) ($item['batchNumber'] ?? '')) . '</td>';
            $html[] = '<td class="right">' . $this->quantity((float) $item['quantity']) . '</td>';
            $html[] = '<td>' . $this->escape((string) $item['unit']) . '</td>';
            if ($showPrices) {
                $html[] = '<td class="right">' . $this->money((float) $item['unitPrice']) . '</td>';
                $html[] = '<td class="right">' . $this->quantity((float) $item['discountPct']) . ' %</td>';
                $html[] = '<td class="right">' . $this->quantity((float) $item['vatRate']) . ' %</td>';
                $html[] = '<td class="right">' . $this->money((float) $item['lineTotal']) . '</td>';
            }
            $html[] = '</tr>';
        }
        $html[] = '</tbody></table>';

        if (!$showPrices) {
            return implode("\n", $html);
        }

        $html[] = '<section class="totals">';
        $html[] = $this->totalRow($labels['amountHt'], $this->money((float) $document['amountHt']), $currency);
        $html[] = $this->totalRow($labels['vatAmount'], $this->money((float) $document['vatAmount']), $currency);
        $html[] = $this->totalRow($labels['totalTtc'], $this->money((float) $document['totalTtc']), $currency, true);
        if ($document['type'] === 'INVOICE') {
            $html[] = $this->totalRow($labels['paid'], $this->money((float) $document['paidAmount']), $currency);
            $html[] = $this->totalRow($labels['remaining'],
                $this->money((float) $document['totalTtc'] - (float) $document['paidAmount']), $currency, true);
        }
        $html[] = '</section>';

        return implode("\n", $html);
    }

    /**
     * @param array<string,mixed> $document
     * @param array<string,string> $labels
     */
    private function statementTable(array $document, array $labels, string $currency): string
    {
        $html = [];
        $html[] = '<table class="lines"><thead><tr>';
        $html[] = '<th>' . $labels['date'] . '</th>';
        $html[] = '<th>' . $labels['document'] . '</th>';
        $html[] = '<th>' . $labels['status'] . '</th>';
        $html[] = '<th class="right">' . $labels['debit'] . '</th>';
        $html[] = '<th class="right">' . $labels['credit'] . '</th>';
        $html[] = '<th class="right">' . $labels['balance'] . '</th>';
        $html[] = '</tr></thead><tbody>';

        $lines = $document['lines'] ?? [];
        if ($lines === []) {
            $html[] = '<tr><td colspan="6" class="empty">—</td></tr>';
        }
        foreach ($lines as $line) {
            $html[] = '<tr>';
            $html[] = '<td>' . $this->escape($this->date($line['documentDate'])) . '</td>';
            $html[] = '<td>' . $this->escape((string) $line['documentNumber']) . '</td>';
            $html[] = '<td>' . $this->escape((string) $line['status']) . '</td>';
            $html[] = '<td class="right">' . $this->money((float) $line['debit']) . '</td>';
            $html[] = '<td class="right">' . $this->money((float) $line['credit']) . '</td>';
            $html[] = '<td class="right">' . $this->money((float) $line['balance']) . '</td>';
            $html[] = '</tr>';
        }
        $html[] = '</tbody></table>';

        $html[] = '<section class="totals">';
        $html[] = $this->totalRow($labels['debit'], $this->money((float) $document['amountHt']), $currency);
        $html[] = $this->totalRow($labels['credit'], $this->money((float) $document['paidAmount']), $currency);
        $html[] = $this->totalRow($labels['balance'], $this->money((float) $document['totalTtc']), $currency, true);
        if (isset($document['extra']['creditLimit'])) {
            $html[] = $this->totalRow($labels['creditLimit'],
                $this->money((float) $document['extra']['creditLimit']), $currency);
        }
        $html[] = '</section>';

        return implode("\n", $html);
    }

    private function totalRow(string $label, string $value, string $currency, bool $strong = false): string
    {
        return '<div class="total-row' . ($strong ? ' strong' : '') . '"><span>' . $label . '</span><span>'
            . $value . ' ' . $this->escape($currency) . '</span></div>';
    }

    private function money(float $value): string
    {
        return number_format($value, 2, ',', ' ');
    }

    private function quantity(float $value): string
    {
        $formatted = number_format($value, 3, ',', ' ');

        return rtrim(rtrim($formatted, '0'), ',');
    }

    private function date(mixed $value): string
    {
        $raw = trim((string) ($value ?? ''));
        if ($raw === '') {
            return '';
        }
        $timestamp = strtotime($raw);

        return $timestamp === false ? $raw : date('d/m/Y', $timestamp);
    }

    private function escape(string $value): string
    {
        return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }

